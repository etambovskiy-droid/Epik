import { useState, useMemo } from 'react';
import { DynamicDashboard, ColumnProfile } from '../../types/dynamicDashboard.ts';
import {
  Table,
  Search,
  Filter,
  Download,
  Calendar,
  Layers,
  BarChart3,
  DollarSign,
  TrendingUp,
  Trash2,
  PieChart,
  Hash,
  Clock,
  Sparkles
} from 'lucide-react';
import * as XLSX from 'xlsx';

interface AutoGeneratedBiDashboardProps {
  dashboard: DynamicDashboard;
  onDeleteDashboard: (id: string) => void;
}

export function AutoGeneratedBiDashboard({
  dashboard,
  onDeleteDashboard
}: AutoGeneratedBiDashboardProps) {
  const [search, setSearch] = useState('');
  const [selectedCategoryCol, setSelectedCategoryCol] = useState<string>(
    dashboard.primaryCategoryColumn || ''
  );
  const [categoryFilterVal, setCategoryFilterVal] = useState<string>('all');
  const [page, setPage] = useState(1);
  const pageSize = 25;

  // Filter columns
  const numericCols = dashboard.columns.filter(c => c.type === 'number');
  const categoryCols = dashboard.columns.filter(c => c.type === 'category' || (c.type === 'text' && c.uniqueCount <= 25));
  const dateCols = dashboard.columns.filter(c => c.type === 'date');

  // Filter rows based on search & category
  const filteredData = useMemo(() => {
    return dashboard.data.filter((row) => {
      // Search across all text fields
      if (search.trim()) {
        const query = search.toLowerCase();
        const matches = Object.values(row).some(v => 
          v !== null && v !== undefined && String(v).toLowerCase().includes(query)
        );
        if (!matches) return false;
      }

      // Category filter
      if (selectedCategoryCol && categoryFilterVal !== 'all') {
        if (String(row[selectedCategoryCol]) !== categoryFilterVal) {
          return false;
        }
      }

      return true;
    });
  }, [dashboard.data, search, selectedCategoryCol, categoryFilterVal]);

  const totalPages = Math.ceil(filteredData.length / pageSize) || 1;
  const paginatedRows = filteredData.slice((page - 1) * pageSize, page * pageSize);

  // Export filtered rows
  const handleExportExcel = () => {
    const ws = XLSX.utils.json_to_sheet(filteredData);
    const wb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(wb, ws, 'PowerBI_Data');
    XLSX.writeFile(wb, `${dashboard.title.replace(/[^a-zA-Z0-9а-яА-ЯіІїЇєЄ]/g, '_')}_export.xlsx`);
  };

  const activeCategoryProfile = dashboard.columns.find(c => c.key === selectedCategoryCol);

  return (
    <div className="space-y-6">
      {/* Dashboard Metadata Banner */}
      <div className="p-4 rounded-2xl bg-[#0b1b3d]/90 border border-blue-900/60 flex flex-col md:flex-row md:items-center md:justify-between gap-3">
        <div className="flex items-center gap-3">
          <div className="w-10 h-10 rounded-xl bg-[#004BB7] flex items-center justify-center text-white font-bold shadow-md">
            <BarChart3 className="w-5 h-5" />
          </div>
          <div>
            <div className="flex items-center gap-2">
              <h2 className="text-base font-bold text-white">{dashboard.title}</h2>
              <span className="px-2 py-0.5 rounded text-[11px] font-mono bg-emerald-950 text-emerald-300 border border-emerald-800">
                Автоматично згенеровано з БІ
              </span>
            </div>
            <p className="text-xs text-blue-200/80 mt-0.5">
              Файл: <strong className="text-white">{dashboard.fileName}</strong> &bull; Завантажено: {dashboard.uploadedAt} &bull; {dashboard.recordCount} рядків, {dashboard.columns.length} колонок
            </p>
          </div>
        </div>

        <div className="flex items-center gap-2 self-end md:self-center">
          <button
            onClick={() => {
              if (window.confirm(`Ви дійсно бажаєте видалити дашборд «${dashboard.title}»?`)) {
                onDeleteDashboard(dashboard.id);
              }
            }}
            className="flex items-center gap-1.5 px-3 py-1.5 rounded-xl text-xs font-medium bg-rose-950/40 hover:bg-rose-900/60 text-rose-300 border border-rose-800/50 transition-colors"
          >
            <Trash2 className="w-3.5 h-3.5" />
            <span>Прибрати дашборд</span>
          </button>
        </div>
      </div>

      {/* 1. Automated Top KPI Metric Cards */}
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-5 gap-3.5">
        {/* Total records */}
        <div className="bg-[#0b1b3d]/80 border border-blue-900/60 rounded-2xl p-4">
          <div className="flex items-center justify-between text-xs text-blue-300 mb-2">
            <span className="font-semibold">Всього записів (Рядків)</span>
            <Hash className="w-4 h-4 text-[#FF7A00]" />
          </div>
          <div className="text-2xl font-bold font-mono text-white">
            {dashboard.recordCount.toLocaleString()}
          </div>
          <div className="text-[11px] text-slate-400 mt-2 font-mono">
            {dashboard.columns.length} структурованих полів
          </div>
        </div>

        {/* First 4 numeric metric cards */}
        {numericCols.slice(0, 4).map((col) => (
          <div key={col.key} className="bg-[#0b1b3d]/80 border border-blue-900/60 rounded-2xl p-4">
            <div className="flex items-center justify-between text-xs text-blue-300 mb-1.5 truncate" title={col.label}>
              <span className="font-semibold truncate">{col.label}</span>
              <TrendingUp className="w-4 h-4 text-[#004BB7] shrink-0" />
            </div>
            <div className="text-2xl font-bold font-mono text-white truncate">
              {col.sum ? col.sum.toLocaleString('uk-UA') : '0'}
            </div>
            <div className="mt-2 text-[11px] text-slate-400 font-mono flex items-center justify-between">
              <span>Сер: {col.avg?.toLocaleString('uk-UA') || '0'}</span>
              <span className="text-emerald-400">Макс: {col.max?.toLocaleString('uk-UA') || '0'}</span>
            </div>
          </div>
        ))}

        {/* Date span card if exists */}
        {dateCols.length > 0 && (
          <div className="bg-[#0b1b3d]/80 border border-blue-900/60 rounded-2xl p-4">
            <div className="flex items-center justify-between text-xs text-blue-300 mb-2 truncate">
              <span className="font-semibold truncate">Період даних ({dateCols[0].label})</span>
              <Calendar className="w-4 h-4 text-emerald-400 shrink-0" />
            </div>
            <div className="text-base font-bold font-mono text-white">
              {dateCols[0].minDate} &ndash; {dateCols[0].maxDate}
            </div>
            <div className="text-[11px] text-slate-400 mt-2 font-mono">
              Часовий діапазон звіту
            </div>
          </div>
        )}
      </div>

      {/* 2. Categorical Distribution Breakdown (Auto generated from BI categories) */}
      {categoryCols.length > 0 && (
        <div className="grid grid-cols-1 lg:grid-cols-2 gap-5">
          {categoryCols.slice(0, 2).map((catCol) => (
            <div key={catCol.key} className="p-5 rounded-2xl bg-[#0b1b3d]/80 border border-blue-900/60 space-y-3.5">
              <div className="flex items-center justify-between pb-2 border-b border-blue-900/40">
                <div className="flex items-center gap-2">
                  <PieChart className="w-4 h-4 text-[#FF7A00]" />
                  <h3 className="text-sm font-bold text-white">
                    Розподіл за полем: <span className="text-blue-300">{catCol.label}</span>
                  </h3>
                </div>
                <span className="text-xs font-mono text-slate-400">
                  {catCol.uniqueCount} унікальних значень
                </span>
              </div>

              <div className="space-y-2.5 max-h-64 overflow-y-auto pr-1">
                {catCol.topCategories?.map((cat) => (
                  <div key={cat.value} className="space-y-1 p-2 rounded-xl bg-[#08142c]/70 border border-blue-900/30">
                    <div className="flex items-center justify-between text-xs font-mono">
                      <span className="text-slate-200 font-semibold truncate max-w-[260px]">
                        {cat.value || 'Порожньо'}
                      </span>
                      <span className="text-white font-bold">
                        {cat.count.toLocaleString()} <span className="text-blue-300 font-normal">({cat.percentage}%)</span>
                      </span>
                    </div>
                    <div className="w-full h-1.5 rounded-full bg-slate-800 overflow-hidden">
                      <div
                        className="h-full rounded-full bg-gradient-to-r from-[#004BB7] to-[#FF7A00]"
                        style={{ width: `${cat.percentage}%` }}
                      />
                    </div>
                  </div>
                ))}
              </div>
            </div>
          ))}
        </div>
      )}

      {/* 3. Interactive Data Table & Filtering */}
      <div className="p-5 rounded-2xl bg-[#0b1b3d]/80 border border-blue-900/60 space-y-4">
        {/* Table Toolbar */}
        <div className="flex flex-col md:flex-row md:items-center md:justify-between gap-3">
          <div className="flex items-center gap-3 flex-1 max-w-md">
            <div className="relative w-full">
              <Search className="w-4 h-4 text-slate-400 absolute left-3 top-2.5" />
              <input
                type="text"
                placeholder="Пошук за будь-яким значенням..."
                value={search}
                onChange={(e) => {
                  setSearch(e.target.value);
                  setPage(1);
                }}
                className="w-full bg-[#08142c] border border-blue-900/70 rounded-xl pl-9 pr-3 py-1.5 text-xs text-white placeholder-slate-500 focus:outline-none focus:border-[#004BB7]"
              />
            </div>
          </div>

          <div className="flex flex-wrap items-center gap-2.5">
            {/* Category Dimension Filter */}
            {categoryCols.length > 0 && activeCategoryProfile && (
              <div className="flex items-center gap-1.5 bg-[#08142c] border border-blue-900/70 rounded-xl px-2.5 py-1 text-xs text-slate-300">
                <Filter className="w-3.5 h-3.5 text-blue-400" />
                <span className="text-[11px] text-slate-400">{activeCategoryProfile.label}:</span>
                <select
                  value={categoryFilterVal}
                  onChange={(e) => {
                    setCategoryFilterVal(e.target.value);
                    setPage(1);
                  }}
                  className="bg-transparent text-xs text-white focus:outline-none cursor-pointer max-w-[140px] truncate"
                >
                  <option value="all" className="bg-[#0b1b3d]">Усі значення</option>
                  {activeCategoryProfile.topCategories?.map((c) => (
                    <option key={c.value} value={c.value} className="bg-[#0b1b3d]">
                      {c.value} ({c.count})
                    </option>
                  ))}
                </select>
              </div>
            )}

            {/* Export Button */}
            <button
              onClick={handleExportExcel}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-xl text-xs font-semibold bg-[#004BB7] hover:bg-blue-600 text-white transition-colors"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Експорт в Excel ({filteredData.length})</span>
            </button>
          </div>
        </div>

        {/* Table Content */}
        <div className="overflow-x-auto rounded-xl border border-blue-900/60 max-h-[500px]">
          <table className="w-full text-left text-xs font-mono">
            <thead>
              <tr className="border-b border-blue-900/70 text-blue-300 text-[11px] bg-[#08142c] sticky top-0 z-10">
                {dashboard.columns.map((col) => (
                  <th key={col.key} className="p-3 font-semibold whitespace-nowrap">
                    {col.label}
                  </th>
                ))}
              </tr>
            </thead>
            <tbody className="divide-y divide-blue-950/60 bg-[#071329]/50">
              {paginatedRows.length === 0 ? (
                <tr>
                  <td colSpan={dashboard.columns.length} className="p-8 text-center text-slate-400 font-mono">
                    Не знайдено записів за вказаними критеріями пошуку
                  </td>
                </tr>
              ) : (
                paginatedRows.map((row, rIdx) => (
                  <tr key={rIdx} className="hover:bg-blue-950/30 transition-colors">
                    {dashboard.columns.map((col) => {
                      const val = row[col.key];
                      const formatted = val !== null && val !== undefined ? String(val) : '—';
                      return (
                        <td key={col.key} className="p-3 text-slate-200 whitespace-nowrap">
                          {col.type === 'number' && typeof val === 'number' ? (
                            <span className="font-semibold text-emerald-300">{val.toLocaleString('uk-UA')}</span>
                          ) : (
                            formatted
                          )}
                        </td>
                      );
                    })}
                  </tr>
                ))
              )}
            </tbody>
          </table>
        </div>

        {/* Pagination controls */}
        {totalPages > 1 && (
          <div className="flex items-center justify-between text-xs text-slate-400 pt-2 font-mono">
            <span>
              Показано {(page - 1) * pageSize + 1} &ndash; {Math.min(page * pageSize, filteredData.length)} з {filteredData.length} рядків
            </span>
            <div className="flex items-center gap-1.5">
              <button
                disabled={page <= 1}
                onClick={() => setPage(p => Math.max(1, p - 1))}
                className="px-2.5 py-1 rounded-lg bg-[#08142c] border border-blue-900/60 text-white disabled:opacity-40 disabled:cursor-not-allowed"
              >
                Попередня
              </button>
              <span className="px-2">Сторінка {page} з {totalPages}</span>
              <button
                disabled={page >= totalPages}
                onClick={() => setPage(p => Math.min(totalPages, p + 1))}
                className="px-2.5 py-1 rounded-lg bg-[#08142c] border border-blue-900/60 text-white disabled:opacity-40 disabled:cursor-not-allowed"
              >
                Наступна
              </button>
            </div>
          </div>
        )}
      </div>
    </div>
  );
}
